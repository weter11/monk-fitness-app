            for (column in ProgramSchemaFixture.columnsNow(table)) {
                assertEquals(
                    "`$table`.`${column.name}`'s declared type",
                    column.type,
                    database.columnType(table, column.name)
                )
                val notNull = database.rows(
                    "SELECT \"notnull\" FROM pragma_table_info('$table') WHERE name = ?",
                    column.name
                ).single().getValue("notnull")
                assertEquals(
                    "`$table`.`${column.name}`'s nullability",
                    if (column.nullable) "0" else "1",
                    notNull
                )
            }
        }
    }

