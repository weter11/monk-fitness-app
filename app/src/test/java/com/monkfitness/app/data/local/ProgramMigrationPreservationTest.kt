    /** SQLite stores the DDL without `IF NOT EXISTS`, so both sides are put in that form. */
    private fun storedForm(sql: String): String =
        ProgramSchemaFixture.normalized(sql).replace("IF NOT EXISTS ", "")

    private fun tablesOf(database: SqliteTestDatabase): List<String> =
        database.tableNames().filterNot { it.startsWith("sqlite_") }.sorted()

