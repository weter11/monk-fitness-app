    @Test
    fun theMigratedSchemaIsTheSchemaRoomExpects() {
        val database = migratedDatabase()
        val schema = database.masterSql()

        for (table in ProgramSchemaFixture.TABLES) {
            assertEquals(
                "`$table` is created exactly as Room's generated DDL declares it at the current version",
                storedForm(ProgramSchemaFixture.expectedCurrentTableDdl(table)),
                storedForm(schema.getValue(table))
            )
        }
        val expectedIndices = ProgramSchemaFixture.TABLES.flatMap { table ->
            ProgramSchemaFixture.INDEXES.getValue(table).map { ProgramSchemaFixture.expectedIndexDdl(table, it) }
        }
        assertEquals(
            "every declared index exists, and no undeclared one does",
            expectedIndices.associateBy { nameOfIndex(it) }.mapValues { storedForm(it.value) },
            schema
                .filterKeys { name -> ProgramSchemaFixture.TABLES.any { name.startsWith("index_${it}_") } }
                .mapValues { storedForm(it.value) }
        )
    }

    private fun nameOfIndex(ddl: String): String =
        ddl.substringAfter("IF NOT EXISTS `").substringBefore("`")

    @Test
    fun theForeignKeysTheEngineRecordsAreTheOwnershipGraphOfTheArchitecture() {
        val database = migratedDatabase()

        for (table in ProgramSchemaFixture.TABLES) {
            // The engine lists a table's keys in its own order, which carries no meaning, so the
            // comparison is by child column: the graph, not the sequence it was written in.
            assertEquals(
                "`$table`'s foreign keys as SQLite records them",
                ProgramSchemaFixture.FOREIGN_KEYS.getValue(table).map {
                    SqliteTestDatabase.ForeignKey(
                        childColumn = it.childColumn,
                        parentTable = it.parentTable,
                        parentColumn = it.parentColumn,
                        onDelete = it.onDelete,
                        onUpdate = "NO ACTION"
                    )
                }.sortedBy { it.childColumn },
                database.foreignKeys(table).sortedBy { it.childColumn }
            )
        }
    }

