    @Test
    fun aCancelledSessionKeepsItsPartialWorkAndDoesNotCompleteItsSlot() {
        val database = migratedDatabase()
        ProgramGraphInserts.insertCompleteProgram(database, "1")
        database.exec("UPDATE `workout_session` SET status = 'CANCELLED', finishedAt = 1700000004000")
        database.exec("UPDATE `program_workout_slot` SET status = 'MISSED'")

        assertEquals("a cancelled session is history, not a deletion", 1, database.count("workout_session"))
        assertEquals(
            "the set it did confirm stays recorded as partial exposure (§12)",
            1,
            database.count("program_set_log")
        )
        assertEquals(
            "and cancelling did not complete the slot it attempted",
            "MISSED",
            database.scalar("SELECT status FROM `program_workout_slot` WHERE slotId = 'slot-1'")
        )
        assertEquals(
            "a cancelled session is not a finished workout",
            "CANCELLED",
            database.scalar("SELECT status FROM `workout_session` WHERE sessionId = 'session-1'")
        )
    }

    @Test
    fun theUpgradeIsTheSameStatementsAVersionSevenDeviceExecutes() {
        // The rewrite-proof behind the tests above: they ran the production migration objects, not a
        // copy of their SQL. This asserts the objects are the ones AppDatabase registers — as one
        // unbroken chain — and that a real engine accepts every statement they contain.
        assertEquals(7, AppDatabase.MIGRATION_7_8.startVersion)
        assertEquals(8, AppDatabase.MIGRATION_7_8.endVersion)
        assertEquals(8, AppDatabase.MIGRATION_8_9.startVersion)
        assertEquals(9, AppDatabase.MIGRATION_8_9.endVersion)
        assertEquals(9, AppDatabase.MIGRATION_9_10.startVersion)
        assertEquals(10, AppDatabase.MIGRATION_9_10.endVersion)
        assertEquals(10, AppDatabase.MIGRATION_10_11.startVersion)
        assertEquals(11, AppDatabase.MIGRATION_10_11.endVersion)

        val database = SqliteTestDatabase.inMemory()
        database.execAll(LegacyV7Schema.TABLE_STATEMENTS)
        try {
            database.migrate(AppDatabase.MIGRATION_7_8)
            database.migrate(AppDatabase.MIGRATION_8_9)
            database.migrate(AppDatabase.MIGRATION_9_10)
            database.migrate(AppDatabase.MIGRATION_10_11)
        } catch (failure: SQLException) {
            throw AssertionError("the migration failed on a real engine: ${failure.message}")
        }
        assertEquals(
            "every target table exists after the chain executed",
            ProgramSchemaFixture.TABLES.size,
            database.tableNames().count { it in ProgramSchemaFixture.TABLES }
        )
        assertEquals(
            "and the last step put the columns it adds on the table it adds them to",
            ProgramSchemaFixture.columnsNow("program_revision").map { it.name },
            database.columnNames("program_revision")
        )
        assertEquals(
            "including the adaptive window bookkeeping the final step appended to the family-state table",
            ProgramSchemaFixture.columnsNow("program_family_progression_state").map { it.name },
            database.columnNames("program_family_progression_state")
        )
    }

    @Test
    fun theFocusCorrectionUpgradesAPopulatedVersionNineDatabaseWithoutInventingAGoal() {
        val database = versionNineDatabase()

        // The version-9 row set: a Program and its revision, written before Goals & Focus had
        // anywhere to be stored.
        database.exec(
            "INSERT INTO `program` (`programId`, `name`, `description`, `source`, `lifecycleStatus`, " +
                "`currentRevisionId`, `createdAt`, `updatedAt`, `plannedStartDate`, `actualStartDate`, " +
                "`archivedAt`) VALUES ('program-9', 'Program', '', 'USER', 'NOT_STARTED', " +
                "'revision-9', 1700000000000, 1700000000000, NULL, NULL, NULL)"
        )
        database.exec(
            "INSERT INTO `program_revision` (`revisionId`, `programId`, `revisionNumber`, `mode`, " +
                "`durationType`, `durationDays`, `scheduleType`, `scheduleWeekdays`, `createdAt`, " +
                "`scheduleSessionsPerWeek`) VALUES ('revision-9', 'program-9', 1, 'GENERATED', " +
                "'INDEFINITE', NULL, 'FLEXIBLE_PER_WEEK', NULL, 1700000000000, 3)"
        )
        val revisionBefore = database.rows("SELECT * FROM `program_revision`").single()
        val schemaBefore = database.masterSql()

        database.migrate(AppDatabase.MIGRATION_9_10)

        val revisionAfter = database.rows("SELECT * FROM `program_revision`").single()
        assertEquals(
            "the row the version-9 database held keeps every value it held",
            revisionBefore,
            revisionAfter.filterKeys { it in revisionBefore.keys }
        )
        assertEquals(
            "and the correction leaves the goal and its targets empty rather than filling in a " +
                "plausible goal: the schema cannot know what the user was building for, and a default " +
                "would state a configuration nobody chose",
            listOf(null, null),
            listOf(revisionAfter["focusGoal"], revisionAfter["focusTargets"])
        )
        assertEquals(
            "no table, index or bookkeeping entry other than the corrected table is rewritten",
            schemaBefore.filterKeys { it != "program_revision" },
            database.masterSql().filterKeys { it != "program_revision" }
        )
        assertEquals(
            "the corrected table gains exactly the columns this step adds, appended",
            ProgramSchemaFixture.columnsNow("program_revision").map { it.name },
            database.columnNames("program_revision")
        )
        assertEquals(
            "and the shipped tables the device already had are still there, untouched",
            "pushup",
            database.scalar("SELECT currentExerciseId FROM `family_progression_state`")
        )
    }

    @Test
    fun theCorrectionUpgradesAPopulatedVersionEightDatabaseWithoutInventingAFrequency() {
        val database = versionEightDatabase()

        // The version-8 row set: a Program and its revision with the schedule form and no frequency,
        // because at version 8 there was nowhere to store one.
        database.exec(
            "INSERT INTO `program` (`programId`, `name`, `description`, `source`, `lifecycleStatus`, " +
                "`currentRevisionId`, `createdAt`, `updatedAt`, `plannedStartDate`, `actualStartDate`, " +
                "`archivedAt`) VALUES ('program-1', 'Program', '', 'USER', 'NOT_STARTED', " +
                "'revision-1', 1700000000000, 1700000000000, NULL, NULL, NULL)"
        )
        database.exec(
            "INSERT INTO `program_revision` (`revisionId`, `programId`, `revisionNumber`, `mode`, " +
                "`durationType`, `durationDays`, `scheduleType`, `scheduleWeekdays`, `createdAt`) " +
                "VALUES ('revision-1', 'program-1', 1, 'MANUAL', 'FIXED_DAYS', 30, " +
                "'FLEXIBLE_PER_WEEK', NULL, 1700000000000)"
        )
        val revisionBefore = database.rows("SELECT * FROM `program_revision`").single()
        val schemaBefore = database.masterSql()

        database.migrate(AppDatabase.MIGRATION_8_9)

        val revisionAfter = database.rows("SELECT * FROM `program_revision`").single()
        assertEquals(
            "the row the version-8 database held keeps every value it held",
            revisionBefore,
            revisionAfter.filterKeys { it in revisionBefore.keys }
        )
        assertEquals(
            "and the correction leaves its frequency empty rather than filling in a plausible number: " +
                "the schema cannot know what the user trained at, and a default would state a schedule " +
                "nobody chose",
            listOf(null),
            listOf(revisionAfter["scheduleSessionsPerWeek"])
        )
        assertEquals(
            "no table, index or bookkeeping entry other than the corrected table is rewritten",
            schemaBefore.filterKeys { it != "program_revision" },
            database.masterSql().filterKeys { it != "program_revision" }
        )
        assertEquals(
            "the corrected table gains exactly the one column this step adds, appended",
            (
                ProgramSchemaFixture.COLUMNS.getValue("program_revision") +
                    ProgramSchemaFixture.columnsAddedBy("MIGRATION_8_9", "program_revision")
                ).map { it.name },
            database.columnNames("program_revision")
        )
        assertEquals(
            "the legacy rows the database held before the correction are untouched too",
            "pushup",
            database.scalar("SELECT currentExerciseId FROM `family_progression_state`")
        )
    }
